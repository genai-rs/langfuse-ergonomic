#[bon]
impl LangfuseClient {
    /// Send ingestion events with the transport of the configured [`crate::ApiVersion`].
    pub(crate) async fn ingest_events(
        &self,
        events: Vec<langfuse_client_base::models::IngestionEvent>,
    ) -> Result<()> {
        use langfuse_client_base::apis::ingestion_api;
        use langfuse_client_base::models::IngestionBatchRequest;

        if self.api_version == crate::ApiVersion::V4 {
            return self.ingest_events_v4(events).await;
        }

        let batch_request = IngestionBatchRequest::builder().batch(events).build();

        // V3 keeps using the (upstream-deprecated) batch ingestion endpoint.
        ingestion_api::ingestion_batch()
            .configuration(self.configuration())
            .ingestion_batch_request(&batch_request)
            .call()
            .await
            .map(|_| ())
            .map_err(crate::error::map_api_error)
    }

    /// Create a new trace
    ///
    /// With [`crate::ApiVersion::V4`] the trace is written as an OpenTelemetry root span and
    /// the returned id is the mapped OTel trace id (see [`crate::otel`]).
    #[builder]
    pub async fn trace(
        &self,
        #[builder(into)] id: Option<String>,
        #[builder(into)] name: Option<String>,
        input: Option<Value>,
        output: Option<Value>,
        metadata: Option<Value>,
        #[builder(default = Vec::new())] tags: Vec<String>,
        #[builder(into)] user_id: Option<String>,
        #[builder(into)] session_id: Option<String>,
        timestamp: Option<DateTime<Utc>>,
        #[builder(into)] release: Option<String>,
        #[builder(into)] version: Option<String>,
        public: Option<bool>,
    ) -> Result<TraceResponse> {
        use langfuse_client_base::models::{
            ingestion_event_trace_event::Type as TraceEventType, IngestionEvent,
            IngestionEventTraceEvent, TraceBody,
        };

        let trace_id = id.unwrap_or_else(|| Uuid::new_v4().to_string());
        let timestamp = timestamp.unwrap_or_else(Utc::now);

        let tags_option = if tags.is_empty() { None } else { Some(tags) };

        let trace_body = TraceBody::builder()
            .id(Some(trace_id.clone()))
            .timestamp(Some(timestamp.fixed_offset()))
            .maybe_name(name.map(Some))
            .maybe_user_id(user_id.map(Some))
            .maybe_input(input.map(Some))
            .maybe_output(output.map(Some))
            .maybe_session_id(session_id.map(Some))
            .maybe_release(release.map(Some))
            .maybe_version(version.map(Some))
            .maybe_metadata(metadata.map(Some))
            .maybe_tags(tags_option.map(Some))
            .maybe_public(public.map(Some))
            .build();

        let event = IngestionEventTraceEvent::builder()
            .body(trace_body)
            .id(Uuid::new_v4().to_string())
            .timestamp(timestamp.to_rfc3339_opts(chrono::SecondsFormat::Millis, true))
            .r#type(TraceEventType::TraceCreate)
            .build();

        self.ingest_events(vec![IngestionEvent::TraceEvent(event)])
            .await
            .map(|_| TraceResponse {
                id: self.effective_trace_id(&trace_id),
                base_url: self.configuration().base_path.clone(),
            })
    }

    /// Get a trace by ID (Langfuse v3 only)
    ///
    /// Calls `GET /api/public/traces/{id}`, which Langfuse v4 removed (Langfuse Cloud:
    /// 2026-11-16). With [`crate::ApiVersion::V4`] this returns [`Error::Configuration`]
    /// without a request; use [`LangfuseClient::trace_observations`] instead.
    #[deprecated(
        note = "Langfuse v3 only; fails with ApiVersion::V4. Use `trace_observations()` or `observations()` instead."
    )]
    pub async fn get_trace(
        &self,
        trace_id: impl Into<String>,
    ) -> Result<langfuse_client_base::models::TraceWithFullDetails> {
        use langfuse_client_base::apis::trace_api;

        self.require_v3("get_trace", "use trace_observations()")?;
        let trace_id = trace_id.into();

        trace_api::trace_get()
            .configuration(self.configuration())
            .trace_id(trace_id.as_str())
            .call()
            .await
            .map_err(crate::error::map_api_error)
    }

    /// List traces with optional filters (Langfuse v3 only)
    ///
    /// Calls `GET /api/public/traces`, which Langfuse v4 removed (Langfuse Cloud:
    /// 2026-11-16). With [`crate::ApiVersion::V4`] this returns [`Error::Configuration`]
    /// without a request; use [`LangfuseClient::observations`] with
    /// `.is_root_observation(true)` instead.
    #[deprecated(
        note = "Langfuse v3 only; fails with ApiVersion::V4. Use `observations().is_root_observation(true)` instead."
    )]
    pub fn list_traces(&self) -> LangfuseClientListTracesBuilder<'_> {
        self.list_traces_v3()
    }

    #[builder(
        builder_type(name = LangfuseClientListTracesBuilder, vis = "pub"),
        start_fn(name = list_traces_v3, vis = "pub(crate)")
    )]
    async fn list_traces_impl(
        &self,
        page: Option<i32>,
        limit: Option<i32>,
        #[builder(into)] user_id: Option<String>,
        #[builder(into)] name: Option<String>,
        #[builder(into)] session_id: Option<String>,
        #[builder(into)] version: Option<String>,
        #[builder(into)] release: Option<String>,
        #[builder(into)] from_timestamp: Option<String>,
        #[builder(into)] to_timestamp: Option<String>,
        #[builder(into)] order_by: Option<String>,
        #[builder(into)] tags: Option<String>,
    ) -> Result<langfuse_client_base::models::Traces> {
        use langfuse_client_base::apis::{trace_api, Error as ApiError};

        self.require_v3(
            "list_traces",
            "use observations().is_root_observation(true)",
        )?;

        let parse_timestamp = |value: String| {
            DateTime::parse_from_rfc3339(&value)
                .map_err(|e| Error::Validation(format!("Trace timestamp must be RFC3339: {e}")))
        };
        let from_timestamp = from_timestamp.map(parse_timestamp).transpose()?;
        let to_timestamp = to_timestamp.map(parse_timestamp).transpose()?;

        // The endpoint is deprecated upstream (Langfuse v3), but it is still what
        // this builder targets.
        let result = trace_api::trace_list()
            .configuration(self.configuration())
            .maybe_page(page.map(i64::from))
            .maybe_limit(limit.map(i64::from))
            .maybe_user_id(user_id.as_deref())
            .maybe_name(name.as_deref())
            .maybe_session_id(session_id.as_deref())
            .maybe_from_timestamp(from_timestamp)
            .maybe_to_timestamp(to_timestamp)
            .maybe_order_by(order_by.as_deref())
            .maybe_tags(tags.map(|tag| vec![tag]))
            .maybe_version(version.as_deref())
            .maybe_release(release.as_deref())
            .call()
            .await;

        result.map_err(|e| match e {
            ApiError::ResponseError(response) => Error::Api(format!(
                "Failed to list traces: status {}: {}",
                response.status, response.content
            )),
            other => Error::Api(format!("Failed to list traces: {other}")),
        })
    }

    /// Delete a trace
    ///
    /// Works with both API versions. With [`crate::ApiVersion::V4`] the id is mapped like
    /// for writes (see [`crate::otel`]).
    pub async fn delete_trace(&self, trace_id: impl Into<String>) -> Result<()> {
        use langfuse_client_base::apis::trace_api;

        let trace_id = self.effective_trace_id(&trace_id.into());

        trace_api::trace_delete()
            .configuration(self.configuration())
            .trace_id(trace_id.as_str())
            .call()
            .await
            .map(|_| ())
            .map_err(|e| {
                crate::error::Error::Api(format!("Failed to delete trace '{trace_id}': {e}"))
            })
    }

    /// Delete multiple traces
    ///
    /// Works with both API versions. With [`crate::ApiVersion::V4`] the ids are mapped like
    /// for writes (see [`crate::otel`]).
    pub async fn delete_multiple_traces(&self, trace_ids: Vec<String>) -> Result<()> {
        use langfuse_client_base::apis::trace_api;
        use langfuse_client_base::models::TraceDeleteMultipleRequest;

        let trace_ids: Vec<String> = trace_ids
            .iter()
            .map(|id| self.effective_trace_id(id))
            .collect();
        let trace_count = trace_ids.len();
        let request = TraceDeleteMultipleRequest::builder()
            .trace_ids(trace_ids)
            .build();

        trace_api::trace_delete_multiple()
            .configuration(self.configuration())
            .trace_delete_multiple_request(&request)
            .call()
            .await
            .map(|_| ())
            .map_err(|e| {
                crate::error::Error::Api(format!("Failed to delete {trace_count} traces: {e}"))
            })
    }
}
